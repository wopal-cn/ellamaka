#!/usr/bin/env bun

import { $ } from "bun"
import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"
import { createSolidTransformPlugin } from "@opentui/solid/bun-plugin"
import { BINARY_NAME } from "@wopal/ellamaka-brand/branding"
import { buildReleaseIdentityForBuild } from "../build-identity"
import { filterTargets, type BuildTarget } from "../build-targets"

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const dir = path.resolve(__dirname, "../../../opencode")
const distDir = path.resolve(__dirname, "../../../../dist")

process.chdir(dir)

const generated = await import("../../../opencode/script/generate.ts")

import { Script } from "../build-env"
import pkg from "../../../opencode/package.json"

// The channel is resolved by build-env (D-03): release builds derive it from
// the version shape, dev builds take the channel passed via ELLAMAKA_CHANNEL
// (build.sh cli --channel main|local; dev.sh sets local), so the binary's
// channel and its database name agree.
const channel = Script.channel

// Step progress helpers — build.sh passes the total step count via env.
// In TTY mode, stepBegin prints an in-progress line (no newline); stepEnd
// clears it and prints the done line. In non-TTY mode, only the result shows.
const stepTotal = process.env.ELLAMAKA_BUILD_STEPS_TOTAL ?? "4"
const isTTY = process.stderr.isTTY
function stepBegin(step: number, label: string, action: string) {
  if (isTTY) process.stderr.write(`  ${step}/${stepTotal}  ${label.padEnd(11)}   ${action}...`)
}
function stepEnd(step: number, label: string, detail: string) {
  if (isTTY) process.stderr.write("\r\x1b[K")
  process.stderr.write(`  ${step}/${stepTotal}  ${label.padEnd(11)}   ✓ ${detail}\n`)
}

// The DSH runtime manifest is verified and regenerated by build.sh
// before invoking this entry. Guard only against a missing file.
const dshManifestPath = path.resolve(__dirname, "../../../ellamaka-cordis/generated/dsh-runtime-manifest.json")
if (!fs.existsSync(dshManifestPath)) {
  console.error("DSH runtime manifest missing — run via scripts/build.sh, or:")
  console.error("  bun packages/ellamaka-cordis/script/generate-dsh-runtime-manifest.ts")
  process.exit(1)
}

// Load migrations from migration directories
const migrationDirs = (
  await fs.promises.readdir(path.join(dir, "migration"), {
    withFileTypes: true,
  })
)
  .filter((entry) => entry.isDirectory() && /^\d{4}\d{2}\d{2}\d{2}\d{2}\d{2}/.test(entry.name))
  .map((entry) => entry.name)
  .sort()

const migrations = await Promise.all(
  migrationDirs.map(async (name) => {
    const file = path.join(dir, "migration", name, "migration.sql")
    const sql = await Bun.file(file).text()
    const match = /^(\d{4})(\d{2})(\d{2})(\d{2})(\d{2})(\d{2})/.exec(name)
    const timestamp = match
      ? Date.UTC(
          Number(match[1]),
          Number(match[2]) - 1,
          Number(match[3]),
          Number(match[4]),
          Number(match[5]),
          Number(match[6]),
        )
      : 0
    return { sql, timestamp, name }
  }),
)

// --platform: "mac" | "linux" | "win" | "mac,linux" etc.
const platformIndex = process.argv.indexOf("--platform")
const platformArg = platformIndex !== -1 ? process.argv[platformIndex + 1] : null

// --arch: "arm64" | "x64" | "arm64,x64" etc.
const archIndex = process.argv.indexOf("--arch")
const archArg = archIndex !== -1 ? process.argv[archIndex + 1] : null

const singleFlag = process.argv.includes("--single")
const baselineFlag = process.argv.includes("--baseline")
const sourcemapsFlag = process.argv.includes("--sourcemaps")
const plugin = createSolidTransformPlugin()
const skipEmbedWebUi = process.argv.includes("--skip-embed-web-ui")
const webUiOptions = ["ellamaka-app", "none"] as const
type WebUiOption = (typeof webUiOptions)[number]
const webUiIndex = process.argv.indexOf("--web-ui")
const webUiArg = webUiIndex === -1 ? "ellamaka-app" : process.argv[webUiIndex + 1]

if (!webUiOptions.some((option) => option === webUiArg)) {
  console.error(`Invalid --web-ui value: ${webUiArg ?? "<missing>"}`)
  console.error(`Expected one of: ${webUiOptions.join(", ")}`)
  process.exit(1)
}

if (skipEmbedWebUi && webUiIndex !== -1 && webUiArg !== "none") {
  console.error(`--skip-embed-web-ui cannot be combined with --web-ui ${webUiArg}`)
  console.error(`Use --web-ui none instead`)
  process.exit(1)
}

const webUi: WebUiOption = skipEmbedWebUi ? "none" : webUiArg === "ellamaka-app" ? "ellamaka-app" : "none"

let webUiWarnings = ""

const createEmbeddedWebUIBundle = async (webUi: Exclude<WebUiOption, "none">) => {
  const appDir = path.join(import.meta.dirname, "../../../", webUi)
  const dist = path.join(appDir, "dist")
  const viteProc = Bun.spawn({ cmd: ["bun", "run", "build"], cwd: appDir, stdout: "pipe", stderr: "pipe" })
  const [viteExit, viteStderr, viteStdout] = await Promise.all([
    viteProc.exited,
    new Response(viteProc.stderr).text(),
    new Response(viteProc.stdout).text(),
  ])
  if (viteExit !== 0) {
    process.stderr.write(viteStderr)
    process.stderr.write(viteStdout)
    throw new Error(`Web UI build failed (exit ${viteExit})`)
  }
  const projectRoot = path.resolve(appDir, "../..")
  webUiWarnings = viteStderr
    .replace(new RegExp(projectRoot + "/", "g"), "")
    .split("\n")
    .filter((l) => l.trim())
    .filter((l) => !l.startsWith("$ "))
    .map((l) => `    ${l}`)
    .join("\n")
  const files = (await Array.fromAsync(new Bun.Glob("**/*").scan({ cwd: dist })))
    .map((file) => file.replaceAll("\\", "/"))
    .filter((file) => !file.endsWith(".map"))
    .sort()
  const imports = files.map((file, i) => {
    const spec = path.relative(dir, path.join(dist, file)).replaceAll("\\", "/")
    return `import file_${i} from ${JSON.stringify(spec.startsWith(".") ? spec : `./${spec}`)} with { type: "file" };`
  })
  const entries = files.map((file, i) => `  ${JSON.stringify(file)}: file_${i},`)
  return [
    `// Import all files as file_$i with type: "file"`,
    ...imports,
    `// Export with original mappings`,
    `export default {`,
    ...entries,
    `}`,
  ].join("\n")
}

stepBegin(2, "web ui", "building")
const embeddedFileMap = webUi === "none" ? null : await createEmbeddedWebUIBundle(webUi)
if (embeddedFileMap) {
  const fileCount = embeddedFileMap.split("\n").filter((l) => l.startsWith("  ")).length
  stepEnd(2, "web ui", `${webUi} · ${fileCount} files embedded`)
  if (webUiWarnings) {
    process.stderr.write(`    ⚠ vite warnings:\n${webUiWarnings}\n`)
  }
}

// Filter the target matrix. filterTargets fails fast on an empty result —
// building zero targets must never look like a successful build.
let targets: BuildTarget[]
try {
  targets = filterTargets({ platformArg, archArg, singleFlag, baselineFlag })
} catch (err) {
  console.error(err instanceof Error ? err.message : String(err))
  process.exit(1)
}

await $`rm -rf ${distDir}`

const binaries: Record<string, string> = {}
if (!singleFlag) {
  await $`bun install --os="*" --cpu="*" @opentui/core@${pkg.dependencies["@opentui/core"]}`
  await $`bun install --os="*" --cpu="*" @parcel/watcher@${pkg.dependencies["@parcel/watcher"]}`
}
for (const item of targets) {
  const name = [
    BINARY_NAME,
    // changing to win32 flags npm for some reason
    item.os === "win32" ? "windows" : item.os,
    item.arch,
    item.avx2 === false ? "baseline" : undefined,
    item.abi === undefined ? undefined : item.abi,
  ]
    .filter(Boolean)
    .join("-")
  stepBegin(3, "binary", "compiling")
  await $`mkdir -p ${distDir}/${name}/bin`

  const localPath = path.resolve(dir, "node_modules/@opentui/core/parser.worker.js")
  const rootPath = path.resolve(dir, "../../node_modules/@opentui/core/parser.worker.js")
  const parserWorker = fs.realpathSync(fs.existsSync(localPath) ? localPath : rootPath)
  const workerPath = "./src/cli/cmd/tui/worker.ts"

  // Use platform-specific bunfs root path based on target OS
  const bunfsRoot = item.os === "win32" ? "B:/~BUN/root/" : "/$bunfs/root/"
  const workerRelativePath = path.relative(dir, parserWorker).replaceAll("\\", "/")

  const buildResult = await Bun.build({
    conditions: ["browser"],
    tsconfig: "./tsconfig.json",
    plugins: [plugin],
    external: ["node-gyp"],
    format: "esm",
    minify: true,
    sourcemap: sourcemapsFlag ? "linked" : "none",
    splitting: true,
    compile: {
      autoloadBunfig: false,
      autoloadDotenv: false,
      autoloadTsconfig: true,
      autoloadPackageJson: true,
      target: name.replace(BINARY_NAME, "bun") as any,
      outfile: `${distDir}/${name}/bin/${BINARY_NAME}`,
      execArgv: [`--user-agent=${BINARY_NAME}/${Script.version}`, "--use-system-ca", "--"],
      windows: {},
    },
    files: embeddedFileMap ? { "opencode-web-ui.gen.ts": embeddedFileMap } : {},
    entrypoints: [
      "./src/bootstrap.ts",
      parserWorker,
      workerPath,
      ...(embeddedFileMap ? ["opencode-web-ui.gen.ts"] : []),
    ],
    define: {
      OPENCODE_VERSION: `'${Script.version}'`,
      OPENCODE_MIGRATIONS: JSON.stringify(migrations),
      ELLAMAKA_MODELS_DEV: generated.modelsData,
      OTUI_TREE_SITTER_WORKER_PATH: bunfsRoot + workerRelativePath,
      OPENCODE_WORKER_PATH: workerPath,
      OPENCODE_CHANNEL: `'${channel}'`,
      OPENCODE_LIBC: item.os === "linux" ? `'${item.abi ?? "glibc"}'` : "",
      // Embed a structured ReleaseIdentity at build time. Release builds
      // (ELLAMAKA_RELEASE=1) with a release-context path produce a release
      // identity; otherwise a development identity is embedded. See
      // docs/DISTRIBUTION.md §5.4.
      //
      // The define must be a JSON *string* literal (double-encoded): the
      // runtime reads it as a string and JSON.parses it. A bare object
      // literal would make OPENCODE_RELEASE_IDENTITY an object at runtime,
      // which release-info.ts rejects with a fallback to the development
      // identity (bun --define inlines the expression as-is).
      OPENCODE_RELEASE_IDENTITY: JSON.stringify(
        JSON.stringify(
          buildReleaseIdentityForBuild({
            isRelease: Script.release,
            version: Script.version,
            channel,
          }),
        ),
      ),
    },
  })
  if (!buildResult.success) {
    if (isTTY) process.stderr.write("\r\x1b[K")
    process.stderr.write(`  3/${stepTotal}  binary        \u2717 build failed\n`)
    for (const log of buildResult.logs ?? []) {
      process.stderr.write(`    ${log.message}\n`)
    }
    process.exit(1)
  }

  stepEnd(3, "binary", name)

  // Smoke test: verify version output for targets matching current platform
  if (item.os === process.platform && item.arch === process.arch && !item.abi) {
    const binaryPath = `${distDir}/${name}/bin/${BINARY_NAME}`
    stepBegin(4, "smoke", "testing")
    try {
      const versionOutput = await $`${binaryPath} --version`.text()
      stepEnd(4, "smoke", versionOutput.trim())
    } catch (e) {
      console.error(`Smoke test failed for ${name}:`, e)
      process.exit(1)
    }
  }

  await $`rm -rf ${distDir}/${name}/bin/tui`
  await Bun.file(`${distDir}/${name}/package.json`).write(
    JSON.stringify(
      {
        name,
        version: Script.version,
        os: [item.os],
        cpu: [item.arch],
      },
      null,
      2,
    ),
  )
  binaries[name] = Script.version
}

export { binaries }
