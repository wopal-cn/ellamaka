type AtPath<Value, Path extends string> = Path extends `${infer First}.${infer Rest}`
  ? First extends keyof Value
    ? AtPath<Value[First], Rest>
    : never
  : Path extends keyof Value
    ? Value[Path]
    : never
type Func = (...args: any[]) => any
type Args<F> = F extends Func ? NonNullable<Parameters<F>[0]> : never
type Field<Value, Key> = Key extends keyof Value ? Value[Key] : never
type Selection<Value, Keys> = Pick<Value, Extract<Keys, keyof Value>>
type Spec = {
  readonly target: string | null
  readonly path?: Readonly<Record<string, string>>
  readonly query?: readonly string[]
  readonly body?: readonly string[]
  readonly whole?: string | null
  readonly params?: boolean
  readonly direct?: boolean
}
type Paths<P, D extends Spec> = D extends { path: infer Paths extends Readonly<Record<string, string>> }
  ? keyof Paths extends never
    ? { path?: never }
    : { path: { [K in keyof Paths]: Field<P, Paths[K]> } }
  : { path?: never }
type Query<P, D extends Spec> = D extends { query: readonly (infer Keys)[] }
  ? { query?: Selection<P, Keys> }
  : { query?: never }
type Body<P, D extends Spec> = D extends { whole: infer Key extends string }
  ? { body?: Field<P, Key> }
  : D extends { body: readonly (infer Keys)[] }
    ? [Keys] extends [never]
      ? { body?: never }
      : { body?: Selection<P, Keys> }
    : { body?: never }
type LegacyInput<F, D extends Spec> = Paths<Args<F>, D> &
  Query<Args<F>, D> &
  Body<Args<F>, D> &
  Options<never> & { client?: Client } & (D extends { direct: true } ? Partial<Args<F>> : unknown)
type WithData<Result> =
  Result extends Promise<infer Value>
    ? Promise<Value extends { data?: infer Data } ? Value & { data: NonNullable<Data> } : Value>
    : Result
type ResultWithError<Result> =
  Result extends Promise<infer Value>
    ? Promise<Value extends { data: unknown } ? Value & { error?: undefined } : Value>
    : Result
type RequiredCall<Input, F extends Func> = {
  (options: Input & { throwOnError: true; responseStyle?: "fields" }): WithData<ResultWithError<ReturnType<F>>>
  (options: Input): ResultWithError<ReturnType<F>>
}
type OptionalCall<Input, F extends Func> = {
  (options: Input & { throwOnError: true; responseStyle?: "fields" }): WithData<ResultWithError<ReturnType<F>>>
  (options?: Input): ResultWithError<ReturnType<F>>
}
